import numpy as np


def add(a, b):
    """Складывает два числа и возвращает результат.
    Базовая операция калькулятора для сложения."""
    return a + b


def subtract(a, b):
    """Вычитает второе число из первого и возвращает результат."""
    return a - b


def multiply(a, b):
    """Умножает два числа и возвращает результат."""
    return a * b


def divide(a, b):
    """Делит первое число на второе и возвращает результат.
    Проверяем делитель на ноль, чтобы избежать ошибки ZeroDivisionError."""
    if b == 0:
        return "Ошибка: деление на ноль!"
    return a / b


def test_add():
    """Тест функции сложения: проверяет корректность на разных типах чисел.
    Убеждаемся, что функция правильно складывает положительные, отрицательные числа и нули."""
    assert add(2, 3) == 5, "Тест провален: 2 + 3 должно быть 5"
    assert add(-1, 1) == 0, "Тест провален: -1 + 1 должно быть 0"
    assert add(0, 0) == 0, "Тест провален: 0 + 0 должно быть 0"
    print("Все тесты функции add() прошли успешно!")


if __name__ == "__main__":
    # Сначала запускаем тест, чтобы убедиться, что сложение работает
    test_add()
    
    # Затем проверяем остальные операции
    print("Сложение: " + str(add(10, 5)))
    print("Вычитание: " + str(subtract(10, 5)))
    print("Умножение: " + str(multiply(10, 5)))
    print("Деление: " + str(divide(10, 5)))

    # Проверяем работу numpy
    arr = np.array([1, 2, 3, 4, 5])
    print("Среднее значение массива: " + str(np.mean(arr)))